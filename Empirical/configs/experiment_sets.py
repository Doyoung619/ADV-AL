    return {
        "datasets": datasets,
        "models": models,
        "methods": methods,
        "initial_labeled_size": initial_labeled_size,
        "acquisition_size": acquisition_size,
        "rounds": rounds,
        "epochs_per_round": epochs_per_round,
        "eval_epsilon": eval_epsilon,
        "seeds": seeds,
    }


